def match_business_term(business_term: str) -> tuple:
    """根据业务语义匹配规则类型。

    Args:
        business_term: 业务术语，如 "性别"、"身份证号码"

    Returns:
        (rule_type, options) 或 None
    """
    if not business_term:
        return None

    for keyword, rule_info in BUSINESS_TERM_RULES.items():
        if keyword in business_term:
            return rule_info

    return None


def get_enum_values(business_term: str) -> list:
    """获取标准枚举值。

    Args:
        business_term: 业务术语

    Returns:
        枚举值列表
    """
    for keyword, values in STANDARD_ENUMS.items():
        if keyword in business_term:
            return values
    return None
